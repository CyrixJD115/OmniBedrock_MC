//! Instance port handling: the port-pair model (P for IPv4, P+1 for IPv6),
//! server.properties seeding/rewriting so both stacks stay in sync, and the
//! host bindability probe used for allocation.

use crate::server::Backend;
use omnibedrock_core::{config::Config, files::atomic_write};

/// The legacy server's UDP port from server.properties, or the Bedrock default.
pub(super) async fn legacy_port(config: &Config) -> u16 {
    let properties = config.bedrock_server_dir.join("server.properties");
    if let Ok(text) = tokio::fs::read_to_string(&properties).await {
        for line in text.lines() {
            if let Some(value) = line.strip_prefix("server-port=")
                && let Ok(port) = value.trim().parse::<u16>()
            {
                return port;
            }
        }
    }
    19132
}

/// A fresh instance's server.properties. A Bedrock server listens on BOTH
/// stacks, and its IPv6 socket is dual-stack: `server-port` and
/// `server-portv6` must DIFFER or BDS collides with itself ("Port may be in
/// use" on a free port). An instance registered at port P therefore occupies
/// the pair P (IPv4) and P+1 (IPv6) — the same layout as a stock BDS install
/// (19132/19133). Beyond the ports, only keys whose BDS default is harmful
/// are pinned, and they differ per backend:
/// - `transport`: Bedrock clients 1.26.60+ removed RakNet entirely, so a
///   raknet instance is unjoinable by any current client — both backends
///   seed nethernet. Endstone since 0.11.15 multiplexes NetherNet onto
///   server-port (TCP AND UDP); vanilla nethernet signals on TCP server-port
///   and plays on UDP ports from `server-udp-ports`.
/// - `server-udp-ports`: NetherNet's external-join mapping. Without this
///   line remote Bedrock clients fail even with the port forwarded
///   (LAN discovery still works, which hides the breakage). Endstone's
///   multiplexer wants `[ip:]external:internal` with internal == server-port;
///   the bare `{external}:{internal}` form covers same-port setups and the
///   operator prefixes an address their players can reach (public IP, or the
///   tailnet IP for Tailscale joins) for off-LAN joins. Vanilla gets the
///   bare-port floor `{port}` — its nethernet mode needs one UDP port per
///   player slot, and widening beyond the floor (plus forwarding it) is a
///   deliberate operator decision the console advisor calls out.
/// - `allow-list=false`: BDS defaults it on, so an empty allowlist spams a
///   warning every boot and silently rejects every join.
pub fn default_properties_text(port: u16, backend: Backend) -> String {
    match backend {
        Backend::Endstone => format!(
            "# Generated by OmniBedrock; safe to edit by hand.\ntransport=nethernet\nallow-list=false\nserver-port={port}\nserver-portv6={v6}\nserver-udp-ports={port}:{port}\n",
            v6 = port + 1
        ),
        Backend::Vanilla => format!(
            "# Generated by OmniBedrock; safe to edit by hand.\ntransport=nethernet\nallow-list=false\nserver-port={port}\nserver-portv6={v6}\nserver-udp-ports={port}\n",
            v6 = port + 1
        ),
    }
}

/// Rewrite/append both port properties in existing server.properties text,
/// preserving every other line, and add the compatibility defaults from
/// [`default_properties_text`] for keys that are entirely absent — an absent
/// key lets the BDS default win, which is exactly what breaks connections.
/// Explicit user values always win. `transport` defaults to nethernet for
/// both backends (clients 1.26.60+ removed RakNet), and a nethernet file
/// without `server-udp-ports` gets the backend's NetherNet mapping appended,
/// since that missing line is what breaks external joins.
///
/// The auto-seeded `server-udp-ports` value also FOLLOWS a port change: when
/// the file's `server-port` differs from `port`, an entry set that is exactly
/// the auto-seed shape (`P`, `P:P`, or `ip:P:P` for the old port P) is
/// rewritten to the new port (ip prefix preserved). Anything else — a custom
/// external port, a range, extra entries — is treated as a deliberate
/// operator choice and never touched. (Pure half of `enforce_instance_port`.)
pub fn enforce_port_in_text(text: &str, port: u16, backend: Backend) -> String {
    // The port the file was pinned to before this call: a `server-udp-ports`
    // value that still names it is stale auto-seed and gets retargeted.
    let previous_port = text.lines().find_map(|line| {
        line.trim()
            .strip_prefix("server-port=")
            .and_then(|v| v.trim().parse::<u16>().ok())
    });
    let mut seen_v4 = false;
    let mut seen_v6 = false;
    let mut seen_transport = false;
    let mut seen_allow_list = false;
    let mut seen_udp_ports = false;
    let mut transport = String::new();
    let mut lines: Vec<String> = text
        .lines()
        .map(|line| {
            let trimmed = line.trim_start();
            if trimmed.starts_with("server-port=") {
                seen_v4 = true;
                format!("server-port={port}")
            } else if trimmed.starts_with("server-portv6=") {
                seen_v6 = true;
                format!("server-portv6={}", port + 1)
            } else {
                if let Some(v) = trimmed.strip_prefix("transport=") {
                    seen_transport = true;
                    // Cut an inline comment; the value itself decides.
                    transport = v.split('#').next().unwrap_or("").trim().to_string();
                } else if trimmed.starts_with("allow-list=") {
                    seen_allow_list = true;
                } else if trimmed.starts_with("server-udp-ports=") {
                    seen_udp_ports = true;
                }
                line.to_string()
            }
        })
        .collect();
    if !seen_v4 {
        lines.push(format!("server-port={port}"));
    }
    if !seen_v6 {
        lines.push(format!("server-portv6={}", port + 1));
    }
    if !seen_transport {
        lines.push("transport=nethernet".into());
        transport = "nethernet".to_string();
    }
    if !seen_allow_list {
        lines.push("allow-list=false".into());
    }
    let nethernet = transport.eq_ignore_ascii_case("nethernet");
    if seen_udp_ports
        && nethernet
        && let Some(old) = previous_port
        && old != port
    {
        let value = lines
            .iter()
            .find_map(|l| l.trim().strip_prefix("server-udp-ports="))
            .unwrap_or_default();
        if let Some(retargeted) = retarget_udp_ports_seed(value, old, port) {
            for line in &mut lines {
                if line.trim_start().starts_with("server-udp-ports=") {
                    *line = format!("server-udp-ports={retargeted}");
                }
            }
        }
    }
    if !seen_udp_ports && nethernet {
        // The NetherNet external-join mapping; without it remote clients
        // fail even with the port forwarded. Never overwrite an explicit
        // value — only fill the absent key.
        match backend {
            Backend::Endstone => lines.push(format!("server-udp-ports={port}:{port}")),
            // Vanilla nethernet binds bare ports/ranges directly; one port
            // is the safe floor (per-player slots are the operator's call).
            Backend::Vanilla => lines.push(format!("server-udp-ports={port}")),
        }
    }
    lines.join("\n") + "\n"
}

/// Retarget an auto-seeded `server-udp-ports` value from port `old` to
/// `new` when EVERY comma entry is exactly the seed shape — bare `old`,
/// `old:old`, or `[ip:]old:old` (any ip prefix, IPv4 or IPv6, is preserved
/// verbatim). Returns `None` when any entry deviates, meaning the operator
/// chose the value and it must not be rewritten.
fn retarget_udp_ports_seed(value: &str, old: u16, new: u16) -> Option<String> {
    let old = old.to_string();
    let new = new.to_string();
    let mut retargeted = Vec::new();
    for entry in value.split(',') {
        let groups: Vec<&str> = entry.trim().rsplit(':').collect();
        let mapped = match groups.len() {
            1 => {
                if groups[0] == old {
                    new.clone()
                } else {
                    return None;
                }
            }
            2 if groups[0] == old && groups[1] == old => format!("{new}:{new}"),
            n if n >= 3 && groups[0] == old && groups[1] == old => {
                // Keep the ip prefix exactly as written (IPv6-safe: split
                // from the right, so every leading group belongs to it).
                let ip = groups[2..].iter().rev().copied().collect::<Vec<_>>();
                format!("{}:{new}:{new}", ip.join(":"))
            }
            _ => return None,
        };
        retargeted.push(mapped);
    }
    Some(retargeted.join(","))
}

/// Do two instances' port pairs [P, P+1] overlap?
pub(super) fn port_pairs_overlap(a: u16, b: u16) -> bool {
    a.abs_diff(b) <= 1
}

/// Seed a fresh instance's server.properties so its port matches the record.
pub(super) async fn seed_server_properties(config: &Config, port: u16, backend: Backend) {
    let path = config.bedrock_server_dir.join("server.properties");
    if tokio::fs::try_exists(&path).await.unwrap_or(false) {
        return;
    }
    let _ = tokio::fs::create_dir_all(&config.bedrock_server_dir).await;
    let _ = tokio::fs::write(&path, default_properties_text(port, backend)).await;
}

/// Keep server.properties in sync with the configured port: both stacks,
/// plus the backend's NetherNet compatibility keys, and retarget a stale
/// auto-seeded `server-udp-ports` value from the file's previous port (see
/// [`enforce_port_in_text`]).
pub async fn enforce_instance_port(config: &Config, port: u16, backend: Backend) {
    let path = config.bedrock_server_dir.join("server.properties");
    let text = tokio::fs::read_to_string(&path).await.unwrap_or_default();
    let _ = atomic_write(&path, enforce_port_in_text(&text, port, backend).as_bytes()).await;
}

/// A port is allocatable only when BOTH stacks can bind it. BDS holds IPv6
/// sockets (`server-portv6`), so an IPv4-only probe would happily hand out a
/// port another instance is already listening on over IPv6. Hosts without
/// any IPv6 (the loopback probe fails) fall back to the IPv4 verdict.
pub(crate) async fn port_bindable(port: u16) -> bool {
    if tokio::net::UdpSocket::bind(("0.0.0.0", port))
        .await
        .is_err()
    {
        return false;
    }
    match tokio::net::UdpSocket::bind(("::", port)).await {
        Ok(_) => true,
        // Bare address, no brackets: tuple ("[::1]", 0) would be treated as
        // a hostname and fail name lookup, breaking the fallback.
        Err(_) => tokio::net::UdpSocket::bind(("::1", 0u16)).await.is_err(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn port_properties_rewrite_preserves_other_lines() {
        // BDS's dual-stack v6 socket requires DIFFERENT v4/v6 ports; an
        // instance at P occupies the pair P (v4) and P+1 (v6). Endstone
        // additionally seeds the NetherNet recipe: transport=nethernet plus
        // the external-join mapping internal == server-port.
        let fresh = default_properties_text(19140, Backend::Endstone);
        assert_eq!(
            fresh,
            "# Generated by OmniBedrock; safe to edit by hand.\ntransport=nethernet\nallow-list=false\nserver-port=19140\nserver-portv6=19141\nserver-udp-ports=19140:19140\n"
        );
        // Vanilla seeds nethernet too (clients 1.26.60+ removed RakNet) with
        // the bare-port floor: one joinable UDP port; widening it is an
        // operator decision the console advisor calls out.
        let vanilla = default_properties_text(19140, Backend::Vanilla);
        assert_eq!(
            vanilla,
            "# Generated by OmniBedrock; safe to edit by hand.\ntransport=nethernet\nallow-list=false\nserver-port=19140\nserver-portv6=19141\nserver-udp-ports=19140\n"
        );
        // Existing file: both keys updated, everything else untouched.
        let existing = "level-name=old\nserver-port=19132\nserver-portv6=19133\nview-distance=32\n";
        let updated = enforce_port_in_text(existing, 19140, Backend::Vanilla);
        assert!(updated.contains("server-port=19140\n"));
        assert!(updated.contains("server-portv6=19141\n"));
        assert!(!updated.contains("19132"));
        assert!(!updated.contains("19133"));
        assert!(updated.contains("level-name=old"));
        assert!(updated.contains("view-distance=32"));
        // Missing keys are appended, not dropped — and the transport default
        // is nethernet on both backends, with the per-backend udp-ports seed.
        let partial = enforce_port_in_text("level-name=x\n", 25565, Backend::Vanilla);
        assert!(partial.contains("server-port=25565"));
        assert!(partial.contains("server-portv6=25566"));
        assert!(partial.contains("transport=nethernet"));
        assert!(partial.contains("allow-list=false"));
        assert!(partial.contains("server-udp-ports=25565\n"));
        // A deliberately chosen transport or allow-list survives enforcement.
        let chosen = enforce_port_in_text(
            "transport=nethernet\nallow-list=true\n",
            25565,
            Backend::Vanilla,
        );
        assert!(chosen.contains("transport=nethernet"));
        assert!(chosen.contains("allow-list=true"));
        // A deliberate raknet choice survives too, and the inert udp-ports
        // key stays absent.
        let raknet = enforce_port_in_text("transport=raknet\n", 25565, Backend::Vanilla);
        assert!(raknet.contains("transport=raknet\n"));
        assert!(!raknet.contains("server-udp-ports"), "{raknet}");
    }

    #[test]
    fn nethernet_instances_get_the_udp_ports_mapping() {
        // THE external-join fix: an Endstone file without server-udp-ports
        // gains the NetherNet mapping (internal == server-port) on enforce.
        let file = "transport=nethernet\nserver-port=24474\nserver-portv6=24475\n";
        let fixed = enforce_port_in_text(file, 24474, Backend::Endstone);
        assert!(fixed.contains("server-udp-ports=24474:24474\n"), "{fixed}");
        assert!(fixed.trim_end().ends_with("server-udp-ports=24474:24474"));
        // An explicit mapping always wins — never appended, never replaced.
        let explicit = enforce_port_in_text(
            "transport=nethernet\nserver-udp-ports=98.30.36.191:24474:24474\n",
            24474,
            Backend::Endstone,
        );
        assert!(explicit.contains("server-udp-ports=98.30.36.191:24474:24474\n"));
        assert_eq!(explicit.matches("server-udp-ports").count(), 1);
        // Vanilla nethernet gets the bare-port floor instead of a mapping
        // (the ip:external:internal form is Endstone-only syntax).
        let vanilla = enforce_port_in_text("transport=nethernet\n", 19132, Backend::Vanilla);
        assert!(vanilla.contains("server-udp-ports=19132\n"), "{vanilla}");
        // raknet leaves the key out entirely: it is inert there.
        let raknet = enforce_port_in_text("transport=raknet\n", 19132, Backend::Endstone);
        assert!(!raknet.contains("server-udp-ports"), "{raknet}");
        // A missing transport key defaults to nethernet, and the udp-ports
        // append follows it (Endstone → nethernet + mapping).
        let seeded = enforce_port_in_text("level-name=x\n", 25565, Backend::Endstone);
        assert!(seeded.contains("transport=nethernet\n"));
        assert!(seeded.contains("server-udp-ports=25565:25565\n"));
        // An inline comment after the value must not hide the transport.
        let commented = enforce_port_in_text(
            "transport=nethernet # kept for 26.60\n",
            24474,
            Backend::Endstone,
        );
        assert!(
            commented.contains("server-udp-ports=24474:24474\n"),
            "{commented}"
        );
    }

    #[test]
    fn stale_udp_ports_seed_follows_the_port() {
        // THE dynamic-seed contract: a server-udp-ports value that is exactly
        // the auto-seed shape for the file's old port is rewritten when the
        // instance's port moves, so the mapping never silently points at a
        // port the server no longer listens on.
        let moved = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=24474:24474\n",
            25565,
            Backend::Endstone,
        );
        assert!(moved.contains("server-port=25565\n"), "{moved}");
        assert!(moved.contains("server-udp-ports=25565:25565\n"), "{moved}");
        // An ip-prefixed seed keeps its prefix (IPv4 and IPv6 both).
        let ipv4 = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=98.30.36.191:24474:24474\n",
            25565,
            Backend::Endstone,
        );
        assert!(
            ipv4.contains("server-udp-ports=98.30.36.191:25565:25565\n"),
            "{ipv4}"
        );
        let ipv6 = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=[::1]:24474:24474\n",
            25565,
            Backend::Endstone,
        );
        assert!(
            ipv6.contains("server-udp-ports=[::1]:25565:25565\n"),
            "{ipv6}"
        );
        // The vanilla floor form follows too.
        let floor = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=24474\n",
            25565,
            Backend::Vanilla,
        );
        assert!(floor.contains("server-udp-ports=25565\n"), "{floor}");
        // Deliberate operator values are never rewritten: a custom external
        // port, multi-entry lists, or a range.
        let custom = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=1.2.3.4:20000:24474\n",
            25565,
            Backend::Endstone,
        );
        assert!(
            custom.contains("server-udp-ports=1.2.3.4:20000:24474\n"),
            "{custom}"
        );
        let multi = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=24474,24476-24480\n",
            25565,
            Backend::Vanilla,
        );
        assert!(
            multi.contains("server-udp-ports=24474,24476-24480\n"),
            "{multi}"
        );
        // No retarget when the port did not change...
        let same = enforce_port_in_text(
            "transport=nethernet\nserver-port=24474\nserver-udp-ports=24474:24474\n",
            24474,
            Backend::Endstone,
        );
        assert!(same.contains("server-udp-ports=24474:24474\n"), "{same}");
        // ...and never on raknet, where the key is inert.
        let raknet = enforce_port_in_text(
            "transport=raknet\nserver-port=24474\nserver-udp-ports=24474:24474\n",
            25565,
            Backend::Endstone,
        );
        assert!(
            raknet.contains("server-udp-ports=24474:24474\n"),
            "{raknet}"
        );
    }

    #[test]
    fn port_pairs_never_overlap() {
        assert!(port_pairs_overlap(19132, 19132));
        assert!(port_pairs_overlap(19132, 19133));
        assert!(port_pairs_overlap(19133, 19132));
        assert!(!port_pairs_overlap(19132, 19134));
        assert!(!port_pairs_overlap(19140, 19132));
    }
}
